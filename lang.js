function applyLanguage(lang) {
  for (const [selector, value] of Object.entries(mapping)) {
    const elements = document.querySelectorAll(selector);
    elements.forEach(el => {
      if (typeof value === 'string') {
        const transObj = translations[value];
        if (transObj && transObj[lang]) {
          el.textContent = transObj[lang];
        }
      } else {
        // complex wrapper
        const transObj = translations[value.key];
        if (transObj && transObj[lang]) {
          const wrap = value.wrap || '';
          el.innerHTML = wrap + transObj[lang];
        }
      }
    });
  }
}

document.addEventListener('DOMContentLoaded', () => {
  const switchers = document.querySelectorAll('.lang-switcher');
  
  // Load saved language or default to English
  const savedLang = localStorage.getItem('study_square_lang') || 'en';
  switchers.forEach(s => s.value = savedLang);
  applyLanguage(savedLang);

  // Handle changes
  switchers.forEach(switcher => {
    switcher.addEventListener('change', (e) => {
      const newLang = e.target.value;
      localStorage.setItem('study_square_lang', newLang);
      
      // Update all other switchers to match
      switchers.forEach(s => s.value = newLang);
      
      applyLanguage(newLang);
    });
  });
});
